def set_language(paragraph, lang_code: str = "ru-RU") -> None:
    for run in paragraph.runs:
        rpr = run._r.get_or_add_rPr()
        if rpr.find(qn("w:noProof")) is None:
            rpr.append(OxmlElement("w:noProof"))
        lang = rpr.find(qn("w:lang"))
        if lang is None:
            lang = OxmlElement("w:lang")
            rpr.append(lang)
        lang.set(qn("w:val"), lang_code)
        lang.set(qn("w:eastAsia"), lang_code)


def translate_paragraphs(doc: Document) -> int:
    changed = 0
    for paragraph in doc.paragraphs:
        text = paragraph.text.strip()
        if not text:
            continue
        for prefix, translation in PARAGRAPH_TRANSLATIONS.items():
            if text.startswith(prefix):
                paragraph.text = translation
                changed += 1
                break
        set_language(paragraph)
    return changed


def translate_tables(doc: Document) -> int:
    changed = 0
    for table in doc.tables:
        for row in table.rows:
            for cell in row.cells:
                value = cell.text.strip()
                if value in TABLE_TRANSLATIONS:
                    cell.text = TABLE_TRANSLATIONS[value]
                    changed += 1
                for paragraph in cell.paragraphs:
                    set_language(paragraph)
    return changed


def main() -> None:
    parser = argparse.ArgumentParser(description="Create Russian version of main_scopus.docx.")
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument("--target", type=Path, default=DEFAULT_TARGET)
    args = parser.parse_args()

    shutil.copy2(args.source, args.target)
    doc = Document(args.target)
    paragraph_count = translate_paragraphs(doc)
    table_count = translate_tables(doc)
    doc.save(args.target)
    print(f"Saved -> {args.target}")
    print(f"Translated paragraphs: {paragraph_count}")
    print(f"Translated table cells: {table_count}")


if __name__ == "__main__":
    main()
